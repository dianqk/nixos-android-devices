#define BTCVSD_CVSD_FIFO_BYTES 2160
static inline int btcvsd_cvsd_pcm_supported(unsigned int setting,
		unsigned int mtu)
{
	/* HCI voice setting: linear, two's-complement PCM16, CVSD air mode. */
	return setting == 0x0060 && mtu >= 120;
}
struct btcvsd_cvsd_fifo {
	unsigned char data[BTCVSD_CVSD_FIFO_BYTES];
	unsigned int head, used, capacity, generation;
};
static inline void btcvsd_cvsd_fifo_reset(struct btcvsd_cvsd_fifo *q,
		unsigned int generation, unsigned int capacity)
{
	q->head = q->used = 0;
	q->generation = generation;
	q->capacity = capacity <= BTCVSD_CVSD_FIFO_BYTES ? capacity : 0;
}
static inline int btcvsd_cvsd_fifo_push(struct btcvsd_cvsd_fifo *q,
		unsigned int generation, const unsigned char *data, unsigned int n)
{
	unsigned int i;
	if (generation != q->generation || !q->capacity || n > q->capacity - q->used)
		return 0;
	for (i = 0; i < n; i++)
		q->data[(q->head + q->used + i) % q->capacity] = data[i];
	q->used += n;
	return 1;
}
static inline int btcvsd_cvsd_fifo_pop(struct btcvsd_cvsd_fifo *q,
		unsigned int generation, unsigned char *data, unsigned int n)
{
	unsigned int i;
	if (generation != q->generation || !q->capacity || n > q->used)
		return 0;
	for (i = 0; i < n; i++)
		data[i] = q->data[(q->head + i) % q->capacity];
	q->head = (q->head + n) % q->capacity;
	q->used -= n;
	return 1;
}
