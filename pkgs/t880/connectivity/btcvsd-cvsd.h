struct btcvsd_cvsd_core {
	btc_s32 accumulator, step;
	btc_u32 history;
};
struct btcvsd_cvsd_tx {
	struct btcvsd_cvsd_core core;
	btc_s16 history[8];
	unsigned int next;
};
struct btcvsd_cvsd_rx {
	struct btcvsd_cvsd_core core;
	btc_s16 history[64];
	unsigned int next, initialized, recovery, uncertain;
};
/* Floor division, matching the reference's arithmetic right shift. All callers
 * have bounded values far from INT64_MIN. */
static inline btc_s64 btcvsd_cvsd_shift(btc_s64 n, unsigned int bits)
{
	return n >= 0 ? n >> bits :
			-((-n + (((btc_s64)1 << bits) - 1)) >> bits);
}
static inline btc_s16 btcvsd_cvsd_sample(btc_s64 n)
{
	return n > 32767 ? 32767 : n < -32768 ? -32768 : (btc_s16)n;
}
static inline void btcvsd_cvsd_core_reset(struct btcvsd_cvsd_core *s)
{
	s->accumulator = 0;
	s->step = 10 * 1024;
	s->history = 0;
}
static inline void btcvsd_cvsd_update(struct btcvsd_cvsd_core *s,
				      unsigned int bit)
{
	btc_s32 limit = 32767 * 1024;
	s->accumulator += bit ? -s->step : s->step;
	if (s->accumulator > limit)
		s->accumulator = limit;
	if (s->accumulator < -limit)
		s->accumulator = -limit;
	s->accumulator -= btcvsd_cvsd_shift(s->accumulator, 5);
	s->history = (s->history << 1) | bit;
	if (!(s->history & 15) || (s->history & 15) == 15) {
		s->step += 10 * 1024;
		if (s->step > 1280 * 1024)
			s->step = 1280 * 1024;
	} else {
		s->step -= s->step >> 10;
		if (s->step < 10 * 1024)
			s->step = 10 * 1024;
	}
}
static inline unsigned char btcvsd_cvsd_encode_byte(struct btcvsd_cvsd_core *s,
						    const btc_s16 input[8])
{
	unsigned int i, byte = 0, bit;
	for (i = 0; i < 8; i++) {
		bit = (btc_s32)input[i] * 1024 < s->accumulator;
		byte = (byte << 1) | bit;
		btcvsd_cvsd_update(s, bit);
	}
	return byte;
}
static inline void btcvsd_cvsd_decode_byte(struct btcvsd_cvsd_core *s,
					   unsigned char byte,
					   btc_s16 output[8])
{
	unsigned int i;
	for (i = 0; i < 8; i++) {
		output[i] = btcvsd_cvsd_shift(s->accumulator, 10);
		btcvsd_cvsd_update(s, (byte >> (7 - i)) & 1);
	}
}
static inline unsigned char btcvsd_cvsd_reverse(unsigned char n)
{
	n = (n >> 4) | (n << 4);
	n = ((n & 0xcc) >> 2) | ((n & 0x33) << 2);
	return ((n & 0xaa) >> 1) | ((n & 0x55) << 1);
}
static inline void btcvsd_cvsd_tx_reset(struct btcvsd_cvsd_tx *s)
{
	unsigned int i;
	btcvsd_cvsd_core_reset(&s->core);
	for (i = 0; i < 8; i++)
		s->history[i] = 0;
	s->next = 0;
}
static inline void btcvsd_cvsd_rx_reset(struct btcvsd_cvsd_rx *s)
{
	unsigned int i;
	btcvsd_cvsd_core_reset(&s->core);
	for (i = 0; i < 64; i++)
		s->history[i] = 0;
	s->next = 0;
	s->initialized = 1;
	s->recovery = 0;
	s->uncertain = 0;
}
/* Return encoded bytes. One PCM16/8k sample becomes eight CVSD bits.
 * Input/output may be unaligned; only the exact requested bytes are touched.
 * lsb_first selects standard transport packing, not bit polarity inversion. */
static inline unsigned int
btcvsd_cvsd_encode(struct btcvsd_cvsd_tx *s, const unsigned char *pcm,
		   unsigned int bytes, unsigned char *output,
		   unsigned int capacity, unsigned int lsb_first)
{
	unsigned int i, j, k, raw, n = bytes / 2;
	btc_s16 high[8];
	btc_s32 value;
	btc_s64 accum;
	if ((bytes & 1) || n > capacity || lsb_first > 1)
		return 0;
	for (i = 0; i < n; i++) {
		raw = pcm[2 * i] | ((unsigned int)pcm[2 * i + 1] << 8);
		value = (raw & 0x8000) ? (btc_s32)raw - 65536 : (btc_s32)raw;
		s->history[s->next] = (btc_s16)value;
		s->next = (s->next + 1) & 7;
		for (k = 0; k < 8; k++) {
			accum = 0;
			for (j = 0; j < 8; j++)
				accum +=
					(btc_s64)s->history[(s->next + j) & 7] *
					btcvsd_cvsd_polyphase[k * 8 + j];
			high[k] = btcvsd_cvsd_sample(
				btcvsd_cvsd_shift(accum, 13));
		}
		output[i] = btcvsd_cvsd_encode_byte(&s->core, high);
		if (lsb_first)
			output[i] = btcvsd_cvsd_reverse(output[i]);
	}
	return n;
}
/* Return PCM bytes. NULL validity means all encoded bytes were received.
 * Per-sample status: 0 received, 1 uncertain reconstruction, 2 known lost.
 * Lost bytes never clock stale encoded SRAM into the decoder. Instead advance
 * FIR phase using zero high-rate samples and reset at the next received span.
 * This is reacquisition, not continuous-state packet concealment. The eight
 * sample FIR flush is not a bound on core convergence: after any loss, all
 * received PCM remains status1 until a new connection resets the decoder. */
static inline unsigned int
btcvsd_cvsd_decode(struct btcvsd_cvsd_rx *s, const unsigned char *input,
		   unsigned int bytes, const unsigned char *valid,
		   unsigned char *pcm, unsigned int capacity,
		   unsigned char *status, unsigned int lsb_first)
{
	unsigned int i, j, raw, good;
	btc_s16 high[8], value;
	btc_s64 accum;
	unsigned char byte;
	if (bytes > capacity / 2 || lsb_first > 1)
		return 0;
	for (i = 0; i < bytes; i++) {
		good = !valid || valid[i];
		if (good && !s->initialized) {
			btcvsd_cvsd_core_reset(&s->core);
			s->initialized = 1;
			s->recovery = 8;
		}
		accum = 0;
		for (j = 0; j < 64; j++)
			accum += (btc_s64)s->history[(s->next + j) & 63] *
				 btcvsd_cvsd_direct[j];
		value = good ? btcvsd_cvsd_sample(
				       btcvsd_cvsd_shift(accum, 16)) :
			       0;
		if (status)
			status[i] = good ? (s->uncertain ? 1 : 0) : 2;
		if (good) {
			byte = lsb_first ? btcvsd_cvsd_reverse(input[i]) :
					   input[i];
			btcvsd_cvsd_decode_byte(&s->core, byte, high);
			if (s->recovery)
				s->recovery--;
		} else {
			for (j = 0; j < 8; j++)
				high[j] = 0;
			s->initialized = 0;
			s->uncertain = 1;
			s->recovery = 8;
		}
		for (j = 0; j < 8; j++) {
			s->history[s->next] = high[j];
			s->next = (s->next + 1) & 63;
		}
		raw = (unsigned short)value;
		pcm[2 * i] = raw;
		pcm[2 * i + 1] = raw >> 8;
	}
	return bytes * 2;
}
static inline unsigned int btcvsd_cvsd_status(const unsigned char *status,
					      unsigned int samples)
{
	unsigned int i, lost = 0, recovering = 0;
	if (!samples)
		return 0;
	for (i = 0; i < samples; i++) {
		lost += status[i] == 2;
		recovering += status[i] == 1;
	}
	return lost == samples ? 2 : lost ? 3 : recovering ? 1 : 0;
}
/* Conventional 3 ms PCM packets keep silence compatible with CVSD consumers.
 * Worker-owned: reset used on each connection generation. Completed bytes stay
 * available until the next push; callers must consume a ready packet first. */
struct btcvsd_cvsd_packet {
	unsigned char pcm[48], status[24];
	unsigned int used;
};
static inline void btcvsd_cvsd_packet_reset(struct btcvsd_cvsd_packet *p)
{
	p->used = 0;
}
static inline int btcvsd_cvsd_packet_push(struct btcvsd_cvsd_packet *p,
		const unsigned char *sample, unsigned char status)
{
	p->pcm[p->used * 2] = sample[0];
	p->pcm[p->used * 2 + 1] = sample[1];
	p->status[p->used++] = status;
	if (p->used != 24)
		return 0;
	p->used = 0;
	return 1;
}
